		// ======================
		// RELATED PRODUCTS
		// ======================
		function loadRelatedProducts() {

			axios.get('/api/products')
			.then(res => {

				const products = res.data.data;

				const related = products
					.filter(p =>

						p.id != currentProduct.id &&
						p.category_id ==
						currentProduct.category_id

					)
					.slice(0, 4);

				renderRelatedProducts(related);

			});
		}


