			// =========================
			// RENDER BRANDS
			// =========================
			function renderBrands() {

				const container =
					document.getElementById(
						"brands-filter"
					);

				container.innerHTML = "";

				allBrands.forEach(brand => {

					container.innerHTML += `

					<div class="input-checkbox">

