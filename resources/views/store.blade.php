// PAGINATION
// =========================
function renderPagination() {

    const pagination =
        document.getElementById(
            "pagination"
        );

    pagination.innerHTML = "";

    const totalPages =
        Math.ceil(
            filteredProducts.length / perPage
        );

    // previous
    if (currentPage > 1) {

        pagination.innerHTML += `
            <li>
                <a href="#"
                   onclick="goToPage(${currentPage - 1})">
                    <i class="fa fa-angle-left"></i>
                </a>
            </li>
        `;
    }

    // pages
    for (let i = 1; i <= totalPages; i++) {

        pagination.innerHTML += `

        <li class="${
            currentPage === i
            ? 'active'
            : ''
        }">

            <a href="#"
               onclick="goToPage(${i})">
                ${i}
            </a>

        </li>
        `;
    }

    // next
    if (currentPage < totalPages) {

        pagination.innerHTML += `
            <li>
                <a href="#"
                   onclick="goToPage(${currentPage + 1})">
                    <i class="fa fa-angle-right"></i>
                </a>
            </li>
        `;
    }
}


// =========================
// CHANGE PAGE
// =========================
function goToPage(page) {

    currentPage = page;

    renderProducts();

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}


// =========================
// CHANGE PER PAGE
// =========================
function changePerPage() {

    perPage = Number(
        document.getElementById(
            "per-page"
        ).value
    );

    currentPage = 1;

    renderProducts();
}


// =========================
// PRODUCTS COUNT
// =========================
function renderProductsCount() {

    const start =
        (currentPage - 1) * perPage + 1;

    const end =
        Math.min(
